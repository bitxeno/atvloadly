// Release build: writes the server's version variables as a generated Go
// file (mygo build composes its own -ldflags, which would override -X flags
// passed through GOFLAGS), then runs mygo build.
import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const version = process.env.VERSION || "1.0.0";
const commit = process.env.COMMIT || "unknown";
const date = (process.env.BUILDDATE || new Date().toISOString().slice(0, 19).replace("T", " "));

const file = `// Code generated by build.mjs; DO NOT EDIT.

package main

import (
	"github.com/bitxeno/atvloadly/internal/app"
	"github.com/bitxeno/atvloadly/internal/app/build"
)

func init() {
	build.Version = "${version}"
	build.Commit = "${commit}"
	build.BuildDate = "${date}"
	build.Mode = "production"
	// app.Version copies the build variables at package init, before this
	// file's init runs; refresh it.
	app.Version = app.AppVersion{Version: "${version}", Commit: "${commit}", BuildDate: "${date}"}
}
`;
writeFileSync("version_gen.go", file);
console.log("$", `version=${version} commit=${commit}`, "mygo build");

const skipDmg = process.platform !== "win32" ? ["-skip-dmg"] : [];
const r = spawnSync("go", ["run", "github.com/egoist/mygo/cmd/mygo", "build", ...skipDmg, ...process.argv.slice(2)], {
  stdio: "inherit",
  env: { ...process.env, CGO_ENABLED: "0" },
});
process.exit(r.status ?? 1);
