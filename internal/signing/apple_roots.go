// appleRoots pins every embedded root to its SHA-256 fingerprint so an edited
// PEM can never become a trust anchor.
var appleRoots = []struct {
	pem    string
	sha256 string
}{
	{appleRootCAPEM, "b0b1730ecbc7ff4505142c49f1295e6eda6bcaed7e2c68c5be91b5a11001f024"},
	{appleRootCAG3PEM, "63343abfb89a6a03ebb57e9b3f5fa7be7c4f5c756f3017b3a8c488c3653e9179"},
}

// appleRootPool returns the pool of the embedded Apple root certificates. It
// fails closed when an embedded certificate does not match its pinned fingerprint.
var appleRootPool = sync.OnceValues(func() (*x509.CertPool, error) {
	pool := x509.NewCertPool()
	for _, root := range appleRoots {
		block, rest := pem.Decode([]byte(root.pem))
		if block == nil || block.Type != "CERTIFICATE" || len(bytes.TrimSpace(rest)) != 0 {
			return nil, fmt.Errorf("embedded Apple root certificate %s is not a single PEM certificate", root.sha256)
		}
		sum := sha256.Sum256(block.Bytes)
		if hex.EncodeToString(sum[:]) != root.sha256 {
			return nil, fmt.Errorf("embedded Apple root certificate %s does not match its pinned fingerprint", root.sha256)
		}
		cert, err := x509.ParseCertificate(block.Bytes)
		if err != nil {
			return nil, fmt.Errorf("embedded Apple root certificate %s cannot be parsed: %w", root.sha256, err)
		}
		pool.AddCert(cert)
	}
	return pool, nil
})
